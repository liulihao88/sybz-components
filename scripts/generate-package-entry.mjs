import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import fg from 'fast-glob'

const root = resolve(import.meta.dirname, '..')
const entries = fg
  .sync(['packages/components/*/index.ts', 'packages/components/company/*/index.ts'], {
    cwd: root,
    ignore: [
      'packages/components/chart/index.ts',
      'packages/components/company/chart/index.ts',
      'packages/components/company/{countBar,countBarOld,objectLine,quotaPie}/index.ts',
    ],
  })
  .map((entry) => {
    const path = entry.replace(/^packages\//, '').replace(/\/index\.ts$/, '')
    const component = path.split('/').at(-1)
    const name = `S${component.charAt(0).toUpperCase()}${component.slice(1)}`
    return { path, name }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const names = new Set()
for (const { name } of entries) {
  if (names.has(name)) throw new Error(`重复的组件导出名称：${name}`)
  names.add(name)
}

const legacyNames = [
  'components',
  'createImageResolver',
  'addIconifyIcon',
  'addIconifyCollection',
  'resetSybzThemeColors',
  'setSybzThemeColors',
  'createSvg',
  'useBoolean',
  'useClickOutside',
  'useCommonProps',
  'useFlexFillSize',
  'useEventListener',
  'useGlobalComponentConfig',
  'GLOBAL_COMPONENT_COMMON_PROPS_KEY',
  'GLOBAL_COMPONENT_CONFIG_KEY',
  'useLoading',
  'usePagination',
  'useRefresh',
  'useStyleProps',
  'resolveStyleProps',
  'resolveStyleColor',
  'resolveThemeColor',
  'styleProps',
  'stylePropsMixin',
  'STYLE_PROP_MAP',
  'SIZE_PRESETS',
]

const lines = [
  '// Generated by scripts/generate-package-entry.mjs. Do not edit this file.',
  "export { default } from './sybz-components-es.js'",
  `export { ${legacyNames.join(', ')} } from './sybz-components-es.js'`,
  ...entries.map(({ name, path }) => `export { default as ${name} } from './${path}.js'`),
  '',
]

const output = resolve(root, 'dist/index.js')
mkdirSync(resolve(root, 'dist'), { recursive: true })
writeFileSync(output, lines.join('\n'))
console.log(`Generated ${entries.length} named component exports in dist/index.js`)
